import fs from 'node:fs/promises';
import {pathToFileURL,fileURLToPath} from 'node:url';
const base=process.argv[2] ? pathToFileURL(process.argv[2]) : import.meta.url;
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const rows=JSON.parse(await fs.readFile(new URL('workbook_inputs.json',base),'utf8'));
const wb=Workbook.create(); const sh=wb.worksheets.add('Parameters');
sh.getRange(`A1:E${rows.length}`).values=rows;
sh.getRange('A1:E1').format.fill='#17365D';
sh.getRange('A1:E1').format.font.color='#FFFFFF';
sh.getRange('A:A').format.columnWidth=19;
sh.getRange('B:B').format.columnWidth=57;
sh.getRange('C:D').format.columnWidth=17;
sh.getRange('E:E').format.columnWidth=64;
sh.getRange(`D2:D${rows.length}`).format.fill='#FFF2CC';
sh.getRange(`D2:D${rows.length}`).setNumberFormat('0.000000');
sh.freezePanes.freezeRows(1);
await wb.recalculate();
console.log((await wb.inspect({kind:'region',sheetId:'Parameters',range:`A${rows.length-2}:E${rows.length}`,maxChars:2500})).ndjson);
await (await SpreadsheetFile.exportXlsx(wb)).save(fileURLToPath(new URL('../Calibrations.xlsx',base)));
const preview=await wb.render({sheetName:'Parameters',range:`A${rows.length-2}:E${rows.length}`,scale:1,format:'png'});
await fs.writeFile(new URL('calibration_preview.png',base),new Uint8Array(await preview.arrayBuffer()));